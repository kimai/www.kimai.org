<?php

/**
 * Syncs roadmap items (feature requests) from our Fider instance into _data/roadmap/.
 *
 * Every store item in _data/store/*.yml with a "roadmap_category" key (a Fider tag slug)
 * results in a file _data/roadmap/<roadmap_category>.yml, containing all open, planned
 * and started posts with that tag, ordered by votes.
 *
 * Usage: FIDER_API_TOKEN=xxx php scripts/update-roadmap.php
 */

include_once __DIR__ . '/../vendor/autoload.php';

use Symfony\Component\Yaml\Yaml;

const FIDER_URL = 'https://roadmap.kimai.org';
const FIDER_STATUSES = ['open', 'started', 'planned'];

$token = getenv('FIDER_API_TOKEN');
if ($token === false || trim($token) === '') {
    fwrite(STDERR, 'Error: Missing Fider API token. Please set the environment variable FIDER_API_TOKEN, e.g.' . PHP_EOL);
    fwrite(STDERR, '       FIDER_API_TOKEN=your-token php scripts/update-roadmap.php' . PHP_EOL);
    fwrite(STDERR, '       You can create an API key in Fider at ' . FIDER_URL . '/settings/api' . PHP_EOL);
    exit(1);
}
$token = trim($token);

$dataDir = realpath(__DIR__ . '/../_data/');
$storeDir = $dataDir . '/store/';
$roadmapDir = $dataDir . '/roadmap/';

if (!is_dir($roadmapDir) && !mkdir($roadmapDir, 0755, true)) {
    fwrite(STDERR, 'Error: Could not create directory ' . $roadmapDir . PHP_EOL);
    exit(1);
}

// collect all categories from the store items
$categories = [];
foreach (glob($storeDir . '*.yml') as $file) {
    $item = Yaml::parseFile($file);
    if (!is_array($item) || empty($item['roadmap_category'])) {
        continue;
    }
    $category = (string) $item['roadmap_category'];
    if (preg_match('/^[a-z0-9][a-z0-9-]*$/', $category) !== 1) {
        fwrite(STDERR, sprintf('Warning: Skipping invalid roadmap_category "%s" in %s', $category, basename($file)) . PHP_EOL);
        continue;
    }
    $categories[$category][] = basename($file, '.yml');
}

if (count($categories) === 0) {
    echo 'No store item with a "roadmap_category" found, nothing to do.' . PHP_EOL;
    exit(0);
}

ksort($categories);
$errors = 0;

foreach ($categories as $category => $storeItems) {
    $url = FIDER_URL . '/api/v1/posts?' . http_build_query([
        'tags' => $category,
        'view' => 'most-wanted',
        'moderation' => 'approved',
        'statuses' => implode(',', FIDER_STATUSES),
        'limit' => '20',
    ]);

    try {
        $posts = fetchJson($url, $token);
    } catch (RuntimeException $ex) {
        fwrite(STDERR, sprintf('Error: Failed loading roadmap items for "%s": %s', $category, $ex->getMessage()) . PHP_EOL);
        $errors++;
        continue;
    }

    $items = [];
    foreach ($posts as $post) {
        // double check, in case the API ignores a filter
        if (!in_array($post['status'] ?? '', FIDER_STATUSES, true)) {
            continue;
        }
        if (isset($post['isApproved']) && $post['isApproved'] === false) {
            continue;
        }
        if (!in_array($category, $post['tags'] ?? [], true)) {
            continue;
        }

        $items[] = [
            'id' => (int) $post['id'],
            'number' => (int) $post['number'],
            'slug' => (string) $post['slug'],
            'title' => trim((string) $post['title']),
            'status' => (string) $post['status'],
            'votesCount' => (int) ($post['votesCount'] ?? 0),
            'description' => trim(str_replace("\r\n", "\n", (string) ($post['description'] ?? ''))),
        ];
    }

    // most votes first, newest (highest number) first on equal votes
    usort($items, function (array $a, array $b): int {
        return [$b['votesCount'], $b['number']] <=> [$a['votesCount'], $a['number']];
    });

    $data = [
        'category' => $category,
        'url' => FIDER_URL . '/?tags=' . rawurlencode($category),
        'items' => $items,
    ];

    $target = $roadmapDir . $category . '.yml';
    $yaml = '# Generated by scripts/update-roadmap.php - do not edit manually' . PHP_EOL
        . Yaml::dump($data, 4, 2, Yaml::DUMP_MULTI_LINE_LITERAL_BLOCK);

    file_put_contents($target, $yaml);
    echo sprintf('%s: %d items (used by: %s)', $category, count($items), implode(', ', $storeItems)) . PHP_EOL;
}

exit($errors > 0 ? 1 : 0);

/**
 * @return array<int, array<string, mixed>>
 */
function fetchJson(string $url, string $token): array
{
    $ch = curl_init();
    curl_setopt($ch, CURLOPT_URL, $url);
    curl_setopt($ch, CURLOPT_FOLLOWLOCATION, true);
    curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
    curl_setopt($ch, CURLOPT_TIMEOUT, 30);
    curl_setopt($ch, CURLOPT_HTTPHEADER, [
        'Accept: application/json',
        'Authorization: Bearer ' . $token,
    ]);

    $body = curl_exec($ch);
    if ($body === false) {
        $error = curl_error($ch);
        curl_close($ch);
        throw new RuntimeException($error);
    }

    $status = curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);

    if ($status === 401 || $status === 403) {
        throw new RuntimeException(sprintf('HTTP %d - is the FIDER_API_TOKEN valid?', $status));
    }
    if ($status !== 200) {
        throw new RuntimeException(sprintf('HTTP %d: %s', $status, substr((string) $body, 0, 200)));
    }

    $json = json_decode($body, true);
    if (!is_array($json)) {
        throw new RuntimeException('Invalid JSON response: ' . json_last_error_msg());
    }

    return $json;
}
